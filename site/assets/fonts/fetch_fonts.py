"""Download IBM Plex Sans + Archivo Narrow (open-source, SIL OFL) and generate
a self-hosted `web/css/fonts.css`, so the app needs NO external font requests at
runtime (important for offline/gym use).

Run once:  python web/assets/fonts/fetch_fonts.py

Sources are Fontsource's jsDelivr CDN (stable, OFL-licensed). If you're offline
and can't run this, the app falls back to system fonts (Arial Narrow / Segoe UI),
which still look close.
"""

from __future__ import annotations

import os
import ssl
import urllib.request

HERE = os.path.dirname(__file__)
CSS_PATH = os.path.normpath(os.path.join(HERE, "..", "..", "css", "fonts.css"))
BASE = "https://cdn.jsdelivr.net/fontsource/fonts"

# (css family, fontsource slug, weights)
FAMILIES = [
    ("IBM Plex Sans", "ibm-plex-sans", [400, 500, 600, 700]),
    ("Archivo Narrow", "archivo-narrow", [600, 700]),
]


def fetch(url: str) -> bytes:
    ctx = ssl.create_default_context()
    req = urllib.request.Request(url, headers={"User-Agent": "badminton-fonts"})
    with urllib.request.urlopen(req, timeout=30, context=ctx) as r:
        return r.read()


def main() -> int:
    faces = []
    for family, slug, weights in FAMILIES:
        for w in weights:
            fname = f"{slug}-latin-{w}.woff2"
            url = f"{BASE}/{slug}@latest/latin-{w}-normal.woff2"
            data = fetch(url)
            with open(os.path.join(HERE, fname), "wb") as fh:
                fh.write(data)
            faces.append(
                f"@font-face{{font-family:'{family}';font-style:normal;"
                f"font-weight:{w};font-display:swap;"
                f"src:url('../assets/fonts/{fname}') format('woff2');}}")
            print(f"  downloaded {fname} ({len(data)} bytes)")
    with open(CSS_PATH, "w", encoding="utf-8") as fh:
        fh.write("/* Self-hosted BYU-style fonts (generated by fetch_fonts.py) */\n")
        fh.write("\n".join(faces) + "\n")
    print(f"wrote {CSS_PATH}")
    print("The pages already link css/fonts.css, so you're set.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
